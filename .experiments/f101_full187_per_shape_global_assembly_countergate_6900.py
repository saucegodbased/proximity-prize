#!/usr/bin/env python3
"""Exact ratio-faithful countergate for per-shape Full187 assembly.

This finite control tests one deliberately overstrong interpretation of the
Full187 Pascal/Hermite program.  For one fixed (r,s) shape, let

  F(X,Y) = C(X) Y^J + sum_{f < M} P_f(X) Y^f,

with the literal tapered widths ``deg P_f < D-W*f`` and
``deg C < D-W*J``.  At every node alpha we impose multiplicity M along the
graph ``Y=U(X)``, i.e. every coefficient of ``t^dx v^dv`` of
``F(alpha+t,U(alpha+t)+v)`` vanishes for ``dx+dv<M``.

The parameters (p,N,W,G,E,M,J,D)=(101,20,9,14,6,4,6,56) retain the target
ratios N=2(W+1), G/N=0.7, J/M=1.5 and U=Xi_E^2.  More importantly, every
residual-bearing adjacent pair passes the same first-fringe *dimension*
gate used at the target.  Exact FLINT rank nevertheless shows that neither
of the two terminal C directions is generated by the complete lower source.

Therefore local first-fringe success does not imply a universal, per-shape,
arbitrary-C global cascade.  This does not test the actual four Full187
packet right-hand sides or cross-shape coupling, which remain viable.
"""

from __future__ import annotations

import hashlib
import json
from math import comb
from pathlib import Path
import resource

from flint import nmod_mat


P = 101
N = 20
W = 9
G = 14
ERRORS = N - G
M = 4
J = 6
D = M * G


def poly_mul(left: tuple[int, ...], right: tuple[int, ...]) -> tuple[int, ...]:
    out = [0] * (len(left) + len(right) - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            out[i + j] = (out[i + j] + a * b) % P
    while len(out) > 1 and out[-1] == 0:
        out.pop()
    return tuple(out)


def poly_pow(base: tuple[int, ...], exponent: int) -> tuple[int, ...]:
    out = (1,)
    power = base
    while exponent:
        if exponent & 1:
            out = poly_mul(out, power)
        exponent //= 2
        if exponent:
            power = poly_mul(power, power)
    return out


def locator(nodes: tuple[int, ...]) -> tuple[int, ...]:
    out = (1,)
    for node in nodes:
        out = poly_mul(out, ((-node) % P, 1))
    return out


def translated_coeff(poly: tuple[int, ...], node: int, order: int) -> int:
    """Coefficient of t^order in poly(node+t)."""
    return sum(
        coefficient * comb(degree, order) * pow(node, degree - order, P)
        for degree, coefficient in enumerate(poly)
        if degree >= order
    ) % P


def primitive_subgroup_nodes() -> tuple[int, ...]:
    # 2 is primitive in F_101; omega=2^5 has order 20.
    omega = pow(2, (P - 1) // N, P)
    nodes = tuple(pow(omega, i, P) for i in range(N))
    assert len(set(nodes)) == N
    assert pow(omega, N, P) == 1
    assert all(pow(omega, d, P) != 1 for d in (1, 2, 4, 5, 10))
    return nodes


def jet_column(
        node: int, x_power: int, y_power: int,
        u_powers: tuple[tuple[int, ...], ...]) -> tuple[int, ...]:
    values = []
    for dx in range(M):
        for dv in range(M - dx):
            if dv > y_power:
                values.append(0)
                continue
            polynomial = (0,) * x_power + u_powers[y_power - dv]
            values.append(
                comb(y_power, dv) * translated_coeff(
                    polynomial, node, dx) % P)
    return tuple(values)


def horizontal_concat(left: nmod_mat, right: nmod_mat) -> nmod_mat:
    assert left.nrows() == right.nrows()
    return nmod_mat(left.nrows(), left.ncols() + right.ncols(), [
        int(left[i, j]) if j < left.ncols()
        else int(right[i, j - left.ncols()])
        for i in range(left.nrows())
        for j in range(left.ncols() + right.ncols())
    ], P)


def first_fringe_dimension_gate() -> tuple[tuple[int, ...], ...]:
    records = []
    for f in range(M - 1):
        width = D - W * f
        depth, fringe = divmod(width, N)
        first_q = depth
        if first_q >= M - f:
            continue
        next_width = D - W * (f + 1)
        next_depth, next_fringe = divmod(next_width, N)
        quotient_rows = N - fringe
        records.append((
            f, first_q, width, depth, fringe,
            next_width, next_depth, next_fringe,
            quotient_rows, fringe + next_fringe - N,
        ))
    assert records == [
        (0, 2, 56, 2, 16, 47, 2, 7, 4, 3),
        (1, 2, 47, 2, 7, 38, 1, 18, 13, 5),
        (2, 1, 38, 1, 18, 29, 1, 9, 2, 7),
    ]
    assert all(record[-1] >= 0 for record in records)
    return tuple(records)


def run() -> dict[str, object]:
    nodes = primitive_subgroup_nodes()
    agreements = nodes[:G]
    errors = nodes[G:]
    xi_e = locator(errors)
    u = poly_pow(xi_e, 2)
    u_powers = tuple(poly_pow(u, exponent) for exponent in range(J + 1))

    rows_per_node = M * (M + 1) // 2
    lower_specs = tuple(
        (x_power, f)
        for f in range(M)
        for x_power in range(D - W * f)
    )
    terminal_width = D - W * J
    terminal_specs = tuple((x_power, J) for x_power in range(terminal_width))
    assert len(lower_specs) == 170
    assert terminal_width == 2

    def matrix(specs: tuple[tuple[int, int], ...]) -> nmod_mat:
        columns = []
        for x_power, y_power in specs:
            column = []
            for node in nodes:
                column.extend(jet_column(node, x_power, y_power, u_powers))
            columns.append(column)
        return nmod_mat(N * rows_per_node, len(columns), [
            columns[column][row]
            for row in range(N * rows_per_node)
            for column in range(len(columns))
        ], P)

    lower = matrix(lower_specs)
    terminal = matrix(terminal_specs)
    augmented = horizontal_concat(lower, terminal)
    lower_rank = lower.rank()
    augmented_rank = augmented.rank()
    individual_gains = tuple(
        horizontal_concat(
            lower,
            nmod_mat(terminal.nrows(), 1,
                     [int(terminal[i, j]) for i in range(terminal.nrows())],
                     P),
        ).rank() - lower_rank
        for j in range(terminal.ncols())
    )
    assert (lower_rank, augmented_rank) == (170, 172)
    assert individual_gains == (1, 1)

    return {
        "scope": (
            "finite exact countergate to universal per-shape arbitrary-C "
            "assembly; not a target-field proof and not an actual-packet test"
        ),
        "field_and_parameters_p_N_W_G_E_M_J_D": (
            P, N, W, G, ERRORS, M, J, D),
        "graph_polynomial": "U=Xi_E^2",
        "agreement_nodes": agreements,
        "error_nodes": errors,
        "first_fringe_dimension_records_"
        "f_q_width_depth_fringe_nextWidth_nextDepth_nextFringe_rows_surplus":
            first_fringe_dimension_gate(),
        "all_residual_adjacent_pairs_pass_dimension_gate": True,
        "all_node_jet_rows": N * rows_per_node,
        "lower_columns_terminal_columns": (
            len(lower_specs), len(terminal_specs)),
        "lower_rank_augmented_rank": (lower_rank, augmented_rank),
        "individual_terminal_rank_gains": individual_gains,
        "decision": (
            "RED_UNIVERSAL_PER_SHAPE_ARBITRARY_C_CASCADE__"
            "PIVOT_TO_ACTUAL_PACKETS_OR_CROSS_SHAPE_COUPLING"
        ),
    }


def main() -> None:
    stable = run()
    canonical = json.dumps(stable, sort_keys=True, separators=(",", ":"))
    print(json.dumps({
        **stable,
        "canonical_sha256": hashlib.sha256(canonical.encode()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "peak_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
