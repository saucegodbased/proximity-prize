P = 101
CASE = (10, 4, 7, 4, 28, 1, 1, 6, 10)


def embedded(poly):
    return F.sparse_embed_x(poly)


def sparse_product(factors):
    out = F.sparse_constant(1)
    for factor, exponent in factors:
        out = F.sparse_mul(out, F.sparse_pow(factor, exponent))
    return out


def shifted_x(source, exponent):
    return {
        (x + exponent, y, r, s, z): coefficient
        for (x, y, r, s, z), coefficient in source.items()
    }


def agreement_rows(literal, image):
    return {
        literal.row_keys[row]: coefficient
        for row, coefficient in image.items()
        if literal.row_keys[row][0] == "C"
        and literal.row_keys[row][1] in literal.actual_agreement
    }


def add_scaled(target, source, scale=1):
    for row, coefficient in source.items():
        value = (target.get(row, 0) + scale * coefficient) % P
        if value:
            target[row] = value
        else:
            target.pop(row, None)


def raw_grade_piece(literal, indices, vector, grade):
    return {
        literal.monomials[source_index]: int(vector[row, 0]) % P
        for row, source_index in enumerate(indices)
        if int(vector[row, 0]) % P
        and sum(literal.monomials[source_index][1:]) == grade
    }


def solve_raw_span(columns, target):
    """Return coefficients whose raw polynomial sum is exactly target."""
    rows = tuple(sorted(
        {row for column in columns for row in column} | set(target),
        key=repr))
    augmented = nmod_mat(len(rows), len(columns) + 1, [
        column.get(row, 0)
        for row in rows for column in tuple(columns) + (target,)
    ], P)
    relations, relation_count = augmented.nullspace()
    relation = next(
        column for column in range(relation_count)
        if int(relations[len(columns), column]) % P)
    last = int(relations[len(columns), relation]) % P
    scale = -pow(last, -1, P)
    coefficients = tuple(
        int(relations[row, relation]) * scale % P
        for row in range(len(columns)))
    reconstructed = {}
    for coefficient, column in zip(coefficients, columns):
        add_scaled(reconstructed, column, coefficient)
    assert reconstructed == target
    return coefficients


def make_generators(literal):
    q = literal.q
    locator = literal.locator
    q1 = F.poly_derivative(q, 1)
    q2 = F.poly_derivative(q, 2)
    l1 = F.poly_derivative(locator, 1)
    l2 = F.poly_derivative(locator, 2)

    v = F.sparse_add(F.Y, F.sparse_mul(F.Z, embedded(q)), -1)
    v1 = F.sparse_add(F.R, F.sparse_mul(F.Z, embedded(q1)), -1)
    v2 = F.sparse_add(F.S, F.sparse_mul(F.Z, embedded(q2)), -1)

    j1 = F.sparse_add(
        F.sparse_mul(embedded(locator), v1),
        F.sparse_mul(embedded(l1), v), -1)

    two_l1_squared_minus_l_l2 = F.poly_add(
        F.poly_mul((2,), F.poly_mul(l1, l1)),
        F.poly_mul(locator, l2), -1)
    j2 = F.sparse_mul(embedded(two_l1_squared_minus_l_l2), v)
    j2 = F.sparse_add(
        j2,
        F.sparse_mul(embedded(F.poly_mul(locator, l1)), v1), -2)
    j2 = F.sparse_add(
        j2,
        F.sparse_mul(embedded(F.poly_mul(locator, locator)), v2))

    return {
        "Lambda": embedded(locator),
        "V": v,
        "J1": j1,
        "J2": j2,
    }


def weighted_order_four_families(literal):
    generators = make_generators(literal)
    weights = (1, 1, 2, 3)
    active = (0, 1, 1, 1)
    names = tuple(generators)
    families = []
    for a_lambda in range(5):
        for a_v in range(5):
            for a_j1 in range(3):
                for a_j2 in range(2):
                    exponents = (a_lambda, a_v, a_j1, a_j2)
                    order = sum(w * a for w, a in zip(weights, exponents))
                    if order != 4:
                        continue
                    active_degree = sum(d * a for d, a in zip(active, exponents))
                    seed = 7 - active_degree
                    source = sparse_product(tuple(
                        (generators[name], exponent)
                        for name, exponent in zip(names, exponents)))
                    source = F.sparse_mul(source, F.sparse_pow(F.Z, seed))
                    label = "*".join(
                        name + (f"^{exponent}" if exponent != 1 else "")
                        for name, exponent in zip(names, exponents) if exponent)
                    families.append((label, exponents, active_degree, seed, source))
    assert len(families) == 11
    return tuple(families)


def one_case(offsets):
    literal = M.build_case(
        "order4_covariant_gate", CASE, 7, 7, 4,
        error_direction_offsets=offsets)
    source_index = {monomial: index
                    for index, monomial in enumerate(literal.monomials)}
    base = [
        literal.columns[index]
        for index, monomial in enumerate(literal.monomials)
        if sum(monomial[1:]) <= 6
    ]
    base_rank = TT.rank(base)

    columns = []
    receipts = []
    for label, exponents, active_degree, seed, source in \
            weighted_order_four_families(literal):
        # Some covariants violate the small chamber's individual R/S caps.
        if not all(monomial in source_index for monomial in source):
            receipts.append({
                "family": label,
                "exponents_Lambda_V_J1_J2": exponents,
                "active_degree_seed": (active_degree, seed),
                "literal_source_legal": False,
            })
            continue
        image = TT.indexed_image(literal, source, source_index)
        contact = agreement_rows(literal, image)
        x_multiples = []
        exponent = 0
        while True:
            shifted = shifted_x(source, exponent)
            if not all(monomial in source_index for monomial in shifted):
                break
            shifted_image = TT.indexed_image(literal, shifted, source_index)
            assert not agreement_rows(literal, shifted_image)
            x_multiples.append(shifted_image)
            exponent += 1
        receipts.append({
            "family": label,
            "exponents_Lambda_V_J1_J2": exponents,
            "active_degree_seed": (active_degree, seed),
            "literal_source_legal": True,
            "base_agreement_contact_support": len(contact),
            "legal_X_multiples": len(x_multiples),
        })
        # Do not silently call an expression a cycle if the local convention
        # or the candidate J2 formula is wrong.
        if not contact:
            columns.extend(x_multiples)

    augmented_rank = TT.rank(base + columns)
    individual = tuple(
        TT.rank(base + columns + [target]) - augmented_rank
        for target in literal.targets[:3])
    joint = TT.rank(base + columns + list(literal.targets[:3])) - augmented_rank
    return {
        "error_direction_offsets": offsets,
        "grade_at_most_six_columns_rank": (len(base), base_rank),
        "retained_cycle_columns": len(columns),
        "cycle_rank_increment": augmented_rank - base_rank,
        "individual_F0_F1_F2_defects": individual,
        "joint_defect": joint,
        "families": receipts,
    }


def offset_raw_module_receipt():
    """Express the formerly missing offset shell in the full covariant module.

    Individual Lambda^4 rows exceed the tiny source window, but their illegal
    heads may cancel against the other centered covariants.  Consequently this
    test operates in the raw polynomial module first and verifies legality only
    after the exact coupled sum is reconstructed.
    """
    literal = M.build_case(
        "order4_covariant_raw_module", CASE, 7, 7, 4,
        error_direction_offsets=(3, 5, 7))
    source_index = {monomial: index
                    for index, monomial in enumerate(literal.monomials)}
    families = weighted_order_four_families(literal)
    multiplier_degree = 8
    raw_columns = []
    column_tags = []
    for family_index, (label, _exponents, _active, _seed, source) in \
            enumerate(families):
        for exponent in range(multiplier_degree + 1):
            raw_columns.append(shifted_x(source, exponent))
            column_tags.append((family_index, label, exponent))

    indices, _contact, _nullity, _image, lifts = U.solve_restricted(literal)
    rhs_receipts = []
    raw_targets = []
    raw_coefficient_vectors = []
    for name, vector in lifts:
        target = raw_grade_piece(literal, indices, vector, 7)
        coefficients = solve_raw_span(raw_columns, target)
        raw_targets.append(target)
        raw_coefficient_vectors.append(coefficients)
        multipliers = []
        for family_index, (label, _exponents, _active, _seed, _source) in \
                enumerate(families):
            values = [0] * (multiplier_degree + 1)
            for coefficient, (index, _tag, exponent) in zip(
                    coefficients, column_tags):
                if index == family_index:
                    values[exponent] = coefficient
            poly = nmod_poly(values, P)
            multipliers.append({
                "family": label,
                "multiplier_degree": poly.degree(),
                "multiplier_coefficients": tuple(
                    int(poly[i]) for i in range(max(0, poly.degree() + 1))),
            })

        assert all(monomial in source_index for monomial in target)
        image = TT.indexed_image(literal, target, source_index)
        assert not agreement_rows(literal, image)
        illegal_occurrences = sum(
            1
            for coefficient, column in zip(coefficients, raw_columns)
            if coefficient
            for monomial, value in column.items()
            if value and monomial not in source_index)
        rhs_receipts.append({
            "normal": name,
            "raw_grade7_support": len(target),
            "raw_grade7_sha256": hashlib.sha256(
                repr(tuple(sorted(target.items()))).encode()).hexdigest(),
            "agreement_contact_support": 0,
            "illegal_individual_occurrences_cancelled_in_coupled_sum":
                illegal_occurrences,
            "covariant_multipliers": multipliers,
        })

    base_target = raw_targets[0]
    pivot = next(iter(base_target))
    scales = []
    for target, coefficients in zip(raw_targets, raw_coefficient_vectors):
        scale = target[pivot] * pow(base_target[pivot], -1, P) % P
        assert target == {
            monomial: coefficient * scale % P
            for monomial, coefficient in base_target.items()
            if coefficient * scale % P
        }
        assert coefficients == tuple(
            coefficient * scale % P
            for coefficient in raw_coefficient_vectors[0])
        scales.append(scale)
    assert tuple(scales) == (1, 11, 46)

    return {
        "generator_count": len(families),
        "multiplier_degree_cap": multiplier_degree,
        "raw_generator_columns": len(raw_columns),
        "all_three_exact_offset_shells_reconstructed": True,
        "single_compound_carrier_scales_F0_F1_F2": tuple(scales),
        "rhs": rhs_receipts,
    }


