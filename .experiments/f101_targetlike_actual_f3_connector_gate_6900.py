#!/usr/bin/env python3
"""Exact targetlike-error connecting-map discriminator for the actual F3.

This is the narrow control left open by
``f101_actual_f3_bicovariant_popov_gate_6900.py``.  That experiment showed
that a module generated by columns which are *individually* in the complete
contact kernel misses the targetlike-error F3 by one rank.  Here we retain
the literal coupled contact-and-four-normal map and ask whether the complete
first source shell closes the actual packet jointly.

The agreement direction is Q=Xi_E^2.  On the three error nodes the received
direction is X^2, the small exact analogue of target X^(|E|-1).  The source
prefix has centered total grade at most J.  The only first-shell derivative
groups are raw shapes (r,s)=(0,0),(1,0),(0,1); no arbitrary terminal column
is introduced.  All ranks are exact over F_101.
"""

from __future__ import annotations

from itertools import combinations
import gc
import hashlib
import json
from pathlib import Path
import resource
import sys
import time

sys.path.insert(0, ".experiments")
import f101_o2_bordered_filtration_mechanism_6900 as BM  # noqa: E402
import f101_o2_xi2_full_kernel_certificate_6900 as C  # noqa: E402
import o2_m60_five_pivot_locator_rhs_falsifier_6900 as F  # noqa: E402


P = 101


def quotient_rank(columns):
    echelon = BM.ColumnEchelon()
    for index, column in enumerate(columns):
        echelon.add(column, index)
    return echelon.rank


def quotient_defects(columns, targets):
    rank = quotient_rank(columns)
    individual = tuple(
        quotient_rank(columns + (target,)) - rank for target in targets)
    joint = quotient_rank(columns + targets) - rank
    return individual, joint


def add_scaled(target, source, scale):
    answer = dict(target)
    for row, coefficient in source.items():
        value = (answer.get(row, 0) + scale * coefficient) % P
        if value:
            answer[row] = value
        else:
            answer.pop(row, None)
    return answer


def source_hash(source):
    return hashlib.sha256(
        repr(tuple(sorted(source.items()))).encode()).hexdigest()


def target_safe_103_shape(r, s):
    return (
        s <= 8
        and r + s + max(0, 3 * s - 17) <= 16
        and (s <= 6 or r + 4 * s <= 32)
    )


def exact_representative(literal, selected, target_index):
    """Extract and re-evaluate one exact selected-source packet lift."""
    columns = [literal.columns[index] for index in selected]
    target = literal.targets[target_index]
    columns.append({row: (-value) % P for row, value in target.items()})
    matrix = BM.T.dense_matrix(columns)
    rank = matrix.rank()
    nullspace, nullity = matrix.nullspace()
    last = len(selected)
    relation = next(
        (column for column in range(nullity)
         if int(nullspace[last, column]) % P),
        None,
    )
    assert relation is not None
    scale = pow(int(nullspace[last, relation]) % P, -1, P)
    coefficients = tuple(
        int(nullspace[row, relation]) * scale % P
        for row in range(last)
    )
    image = {}
    solution = {}
    for index, coefficient in zip(selected, coefficients):
        if not coefficient:
            continue
        image = add_scaled(image, literal.columns[index], coefficient)
        solution[literal.monomials[index]] = coefficient
    assert image == target
    assert not any(
        literal.row_keys[row][0] == "C" for row in image
    )
    grades = {}
    shapes = {}
    for monomial in solution:
        grade = sum(monomial[1:])
        shape = (monomial[2], monomial[3])
        grades[grade] = grades.get(grade, 0) + 1
        shapes[shape] = shapes.get(shape, 0) + 1
    receipt = {
        "selected_columns": len(selected),
        "selected_matrix_rank": rank,
        "selected_augmented_nullity": nullity,
        "representative_support": len(solution),
        "representative_sha256": source_hash(solution),
        "used_centered_total_grades": tuple(sorted(grades.items())),
        "used_derivative_shapes": tuple(sorted(shapes.items())),
        "used_first_shell_shapes": tuple(sorted({
            (monomial[2], monomial[3])
            for monomial in solution
            if sum(monomial[1:]) == C.JET + 1
        })),
        "literal_coupled_re_evaluation_equals_F3_target": True,
        "literal_nonzero_contact_rows_after_re_evaluation": 0,
    }
    del matrix, nullspace
    gc.collect()
    return receipt


def analyze():
    n, w, agreement_count, m, degree, slope, curvature, jet, seed = C.CASE
    assert C.CASE == (11, 5, 8, 4, 32, 1, 1, 6, 10)
    xi_error, agreement_direction = C.xi_and_q()
    error_direction = (0, 0, 1)  # X^2 = small analogue of X^(|E|-1).
    offsets = tuple(
        (F.poly_eval(error_direction, node)
         - F.poly_eval(agreement_direction, node)) % P
        for node in C.ERROR
    )

    literal = BM.build_case(
        "primary_n11_targetlike_error_actual_F3_connector",
        C.CASE,
        actual_agreement_count=agreement_count,
        anchor_count=agreement_count,
        normal_coordinates=4,
        error_direction_offsets=offsets,
    )
    assert literal.q == agreement_direction
    assert literal.actual_agreement == C.AGREEMENT
    assert tuple(range(agreement_count, n)) == C.ERROR

    prefix = tuple(
        index for index, monomial in enumerate(literal.monomials)
        if sum(monomial[1:]) <= jet
    )
    prefix_echelon = BM.ColumnEchelon()
    for index in prefix:
        prefix_echelon.add(literal.columns[index], index)
    target_residues = tuple(
        prefix_echelon.reduce(target) for target in literal.targets)

    shell_groups = {}
    for index, monomial in enumerate(literal.monomials):
        if sum(monomial[1:]) == jet + 1:
            shell_groups.setdefault((monomial[2], monomial[3]), []).append(
                index)
    shell_groups = {
        shape: tuple(indices)
        for shape, indices in sorted(shell_groups.items())
    }
    assert tuple(shell_groups) == ((0, 0), (0, 1), (1, 0))
    assert all(target_safe_103_shape(*shape) for shape in shell_groups)
    shell_residues = {
        shape: tuple(prefix_echelon.reduce(literal.columns[index])
                     for index in indices)
        for shape, indices in shell_groups.items()
    }

    group_receipts = []
    for shape, residues in shell_residues.items():
        group_receipts.append({
            "derivative_shape_r_s": shape,
            "raw_shell_columns": len(shell_groups[shape]),
            "raw_shell_quotient_rank": quotient_rank(residues),
            "F0_F1_F2_F3_individual_and_joint_defects":
                quotient_defects(residues, target_residues),
            "actual_F3_defect": quotient_defects(
                residues, (target_residues[3],))[1],
        })

    subset_receipts = []
    shapes = tuple(shell_groups)
    for size in range(1, len(shapes) + 1):
        for subset in combinations(shapes, size):
            residues = tuple(
                residue for shape in subset
                for residue in shell_residues[shape]
            )
            subset_receipts.append({
                "shapes": subset,
                "raw_columns": sum(len(shell_groups[shape])
                                   for shape in subset),
                "F0_F1_F2_F3_individual_and_joint_defects":
                    quotient_defects(residues, target_residues),
                "actual_F3_defect": quotient_defects(
                    residues, (target_residues[3],))[1],
            })

    f3_closing = tuple(
        row["shapes"] for row in subset_receipts
        if row["actual_F3_defect"] == 0
    )
    f3_minimal = tuple(
        subset for subset in f3_closing
        if not any(set(other) < set(subset) for other in f3_closing)
    )
    packet_closing = tuple(
        row["shapes"] for row in subset_receipts
        if row["F0_F1_F2_F3_individual_and_joint_defects"][1] == 0
    )
    packet_minimal = tuple(
        subset for subset in packet_closing
        if not any(set(other) < set(subset) for other in packet_closing)
    )

    decisive_shapes = ((0, 0), (1, 0))
    decisive_indices = prefix + tuple(
        index for shape in decisive_shapes for index in shell_groups[shape]
    )
    f3_representative = exact_representative(
        literal, decisive_indices, target_index=3)
    assert f3_representative["used_first_shell_shapes"] == decisive_shapes

    # Canonical centered carriers are tested as honest linear combinations
    # of raw shell columns.  Their failure would distinguish a connecting-map
    # family from a single-factor extrapolation.
    centered = F.sparse_add(
        F.Y,
        F.sparse_mul(F.Z, F.sparse_embed_x(agreement_direction)),
        -1,
    )
    support_index = {
        monomial: index for index, monomial in enumerate(literal.monomials)
    }
    centered_receipts = []
    centered_residues = []
    for r, s in shapes:
        z = jet + 1 - m - r - s
        assert z >= 0
        carrier = F.sparse_mul(
            F.sparse_pow(centered, m), F.sparse_pow(F.R, r))
        carrier = F.sparse_mul(carrier, F.sparse_pow(F.S, s))
        carrier = F.sparse_mul(carrier, F.sparse_pow(F.Z, z))
        assert all(monomial in support_index for monomial in carrier)
        coupled_image = {}
        for monomial, coefficient in carrier.items():
            coupled_image = add_scaled(
                coupled_image,
                literal.columns[support_index[monomial]],
                coefficient,
            )
        residue = prefix_echelon.reduce(coupled_image)
        centered_residues.append(residue)
        centered_receipts.append({
            "derivative_shape_r_s": (r, s),
            "formula": f"R^{r} S^{s} (Y-QZ)^{m} Z^{z}",
            "source_support": len(carrier),
            "source_sha256": source_hash(carrier),
            "quotient_residue_support": len(residue),
            "actual_F3_defect": quotient_defects(
                (residue,), (target_residues[3],))[1],
        })
    centered_packet_defects = quotient_defects(
        tuple(centered_residues), target_residues)

    # Independent full-source control: it distinguishes failure of the shell
    # gate from failure of the actual packet in this chamber.
    full_echelon = BM.ColumnEchelon()
    for index, column in enumerate(literal.columns):
        full_echelon.add(column, index)
    full_defects = tuple(
        int(bool(full_echelon.reduce(target))) for target in literal.targets)

    # Find the first whole centered grade at which actual F3 closes, without
    # adding any non-source column.
    staged = BM.ColumnEchelon()
    grade_receipts = []
    for grade in range(seed + 1):
        indices = tuple(
            index for index, monomial in enumerate(literal.monomials)
            if sum(monomial[1:]) == grade
        )
        before = staged.rank
        for index in indices:
            staged.add(literal.columns[index], index)
        grade_receipts.append({
            "centered_total_grade": grade,
            "columns": len(indices),
            "rank_increment": staged.rank - before,
            "rank": staged.rank,
            "actual_F3_defect": int(bool(staged.reduce(literal.targets[3]))),
            "packet_individual_defects": tuple(
                int(bool(staged.reduce(target))) for target in literal.targets),
        })

    terminal_deletion_candidates = tuple(
        monomial for monomial in literal.monomials
        if sum(monomial[1:4]) == jet and sum(monomial[1:]) == seed
    )
    forbidden_terminal = tuple(
        monomial for monomial in terminal_deletion_candidates
        if not target_safe_103_shape(monomial[2], monomial[3])
    )
    assert not forbidden_terminal

    return {
        "scope": (
            "exact F101 targetlike-error actual-F3 coupled connector gate; "
            "finite chamber, not a Full187 theorem or submission"
        ),
        "field_and_parameters_n_w_g_m_D_s_t_J_L": (P, *C.CASE),
        "agreement_nodes": C.AGREEMENT,
        "error_nodes": C.ERROR,
        "agreement_direction_Q_equals_XiE_squared": agreement_direction,
        "error_direction_coefficients": error_direction,
        "literal_error_offsets_from_Q": offsets,
        "actual_packet": "F3=B*(Y-Z*q_H)",
        "source_columns": len(literal.columns),
        "source_monomials_sha256": hashlib.sha256(
            repr(literal.monomials).encode()).hexdigest(),
        "coupled_row_count": len(literal.row_keys),
        "prefix_columns_and_rank": (len(prefix), prefix_echelon.rank),
        "prefix_packet_residue_supports": tuple(map(len, target_residues)),
        "prefix_packet_quotient_rank": quotient_rank(target_residues),
        "first_shell_shape_groups": tuple(group_receipts),
        "first_shell_shape_subsets": tuple(subset_receipts),
        "inclusion_minimal_first_shell_shapes_closing_actual_F3": f3_minimal,
        "inclusion_minimal_first_shell_shapes_closing_all_four":
            packet_minimal,
        "exact_actual_F3_prefix_plus_pure_slope_representative":
            f3_representative,
        "canonical_centered_carriers": tuple(centered_receipts),
        "canonical_centered_carriers_packet_defects": centered_packet_defects,
        "full_source_rank": full_echelon.rank,
        "full_source_packet_individual_defects": full_defects,
        "whole_grade_staging": tuple(grade_receipts),
        "safe103_analogue": {
            "terminal_face_candidate_count": len(
                terminal_deletion_candidates),
            "forbidden_terminal_face_count": len(forbidden_terminal),
            "all_first_shell_shapes_target_safe103": True,
        },
        "decision": (
            "FIRST_SHELL_COUPLED_CONNECTOR_GREEN"
            if f3_minimal else
            "FIRST_SHELL_RED_BUT_FULL_SOURCE_GREEN"
            if full_defects[3] == 0 else
            "ACTUAL_F3_FULL_SOURCE_RED"
        ),
    }


def main():
    started = time.monotonic()
    BM.PRIME = BM.T.PRIME = BM.F.PRIME = F.PRIME = P
    stable = analyze()
    canonical = json.dumps(stable, sort_keys=True, separators=(",", ":"))
    result = {
        **stable,
        "canonical_sha256": hashlib.sha256(canonical.encode()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "runtime_receipt": {
            "elapsed_seconds": round(time.monotonic() - started, 6),
            "peak_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
            "external_memory_cap_bytes": 3 * 1024**3,
        },
    }
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
