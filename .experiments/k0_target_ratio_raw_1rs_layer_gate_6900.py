#!/usr/bin/env python3
"""Exact raw derivative-layer discriminator in target-ratio controls.

This is the focused survivor test after the high-Y transport failed.  In the
two deterministic constant-T/equal-mismatch controls, compare the nested raw
families generated by derivative shapes

    1=(R^0 S^0), R, S, R^2.

The full raw contact matrix is built once per profile and exact submatrices
are used thereafter.  There is no random or parameter search.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import resource
import sys
import time

from flint import nmod_mat

sys.path.insert(0, ".experiments")
from higher_jet_literal_matrix import translated_column  # noqa: E402
import k0_target_ratio_constant_t_gate_6900 as Gate  # noqa: E402


P = Gate.P
K0 = Gate.K0


def select_columns(matrix: nmod_mat, columns: tuple[int, ...]) -> nmod_mat:
    return nmod_mat(
        matrix.nrows(), len(columns),
        [int(matrix[i, j])
         for i in range(matrix.nrows()) for j in columns], P)


def full_contact(profile: K0.Profile, receipt: K0.Receipt, monomials):
    sparse = []
    for xp, yp, rp, sp, zp in monomials:
        column = {}
        for node in receipt.nodes:
            expansion = translated_column(
                xp, (yp, rp, sp), zp, node, receipt.u0[node],
                receipt.u1[node], profile.m, 2, P)
            for term, value in expansion.items():
                if value:
                    column[(node, term)] = value
        sparse.append(column)
    rows = tuple(sorted(set().union(*(set(column) for column in sparse)), key=repr))
    return nmod_mat(
        len(rows), len(sparse),
        [sparse[j].get(row, 0)
         for row in rows for j in range(len(sparse))], P)


def full_boundary(receipt: K0.Receipt, monomials, x: int) -> nmod_mat:
    gradients = tuple(K0.monomial_gradient_polys(monomial, receipt)
                      for monomial in monomials)
    return nmod_mat(
        4, len(monomials),
        [int(gradients[j][coordinate](x))
         for coordinate in range(4) for j in range(len(monomials))], P)


def compatible_basis(image: nmod_mat) -> tuple[tuple[int, ...], ...]:
    padded, nullity = image.transpose().nullspace()
    return tuple(tuple(int(padded[i, j]) for i in range(4))
                 for j in range(nullity))


def run(profile: K0.Profile) -> dict[str, object]:
    receipt = Gate.constant_t_receipt(profile)
    monomials = K0.support(profile)
    contact = full_contact(profile, receipt, monomials)
    boundary = full_boundary(receipt, monomials, profile.n)
    families = (
        ("raw_1", {(0, 0)}),
        ("raw_1_S", {(0, 0), (0, 1)}),
        ("raw_1_S_R2", {(0, 0), (0, 1), (2, 0)}),
        ("raw_1_R", {(0, 0), (1, 0)}),
        ("raw_1_R_R2", {(0, 0), (1, 0), (2, 0)}),
        ("raw_1_R_S", {(0, 0), (1, 0), (0, 1)}),
        ("complete_raw_1_R_S_R2", {(0, 0), (1, 0), (0, 1), (2, 0)}),
    )
    answers = []
    for name, shapes in families:
        columns = tuple(j for j, (_, _, rp, sp, _) in enumerate(monomials)
                        if (rp, sp) in shapes)
        cmat = select_columns(contact, columns)
        bmat = select_columns(boundary, columns)
        kernel, nullity = cmat.nullspace()
        rank = cmat.rank()
        assert rank + nullity == len(columns)
        image = bmat * kernel
        gain = image.rank()
        answers.append({
            "family": name,
            "derivative_shapes_R_S": tuple(sorted(shapes)),
            "columns_contact_rank_kernel_dimension_boundary_gain": (
                len(columns), rank, nullity, gain),
            "compatible_boundary_dimension": 4 - gain,
            "compatible_boundary_basis_at_X": compatible_basis(image),
        })
    expected = {
        5: (
            (1200, 1200, 0, 0),
            (2112, 2112, 0, 0),
            (2728, 2728, 0, 0),
            (2076, 2038, 38, 3),
            (2692, 2601, 91, 3),
            (2988, 2916, 72, 4),
            (3604, 3418, 186, 4),
        ),
        6: (
            (1560, 1560, 0, 0),
            (2760, 2760, 0, 0),
            (3600, 3600, 0, 0),
            (2724, 2713, 11, 3),
            (3564, 3508, 56, 3),
            (3924, 3895, 29, 4),
            (4764, 4635, 129, 4),
        ),
    }
    assert tuple(row[
        "columns_contact_rank_kernel_dimension_boundary_gain"]
        for row in answers) == expected[profile.m]
    return {
        "profile_n_w_g_m_B_s_U_L_k_n0": tuple(profile.__dict__.values()),
        "boundary_X": profile.n,
        "families": tuple(answers),
    }


def main() -> None:
    started = time.monotonic()
    payload = {
        "scope": (
            "deterministic raw derivative-shape ablation in two target-ratio "
            "constant-T controls; no parameter/random search"
        ),
        "field": "F_101",
        "verdict": (
            "GREEN finite structural survivor: raw {1,R} creates gain three; "
            "raw S, and not R^2, supplies the fourth direction in both controls"
        ),
        "cases": (run(Gate.EXACT), run(Gate.CEILING)),
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    payload["canonical_sha256"] = hashlib.sha256(canonical.encode()).hexdigest()
    payload["script_sha256"] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    payload["runtime"] = {
        "seconds": round(time.monotonic() - started, 3),
        "peak_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
    }
    print(json.dumps(payload, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
